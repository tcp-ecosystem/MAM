/**
 * Target Handler Tests
 */

import { describe, it, expect } from 'vitest';
import { PythonTarget } from '../src/targets/python.js';
import { JavaScriptTarget } from '../src/targets/javascript.js';
import { GoTarget } from '../src/targets/go.js';
import { OpenAITarget } from '../src/targets/openai.js';
import { LangGraphTarget } from '../src/targets/langgraph.js';
import { CrewAITarget } from '../src/targets/crewai.js';
import { type V2ModuleNode, type CompilerConfig } from '@mam/ast';

const loc = { start: { line: 1, column: 0 }, end: { line: 5, column: 0 } };

function makeModule(overrides: Partial<V2ModuleNode> & { name: string }): V2ModuleNode {
  return {
    type: 'ModuleNode',
    moduleType: 'agent',
    name: 'test-module',
    role: 'Test agent',
    goal: 'Test goal',
    location: loc,
    ...overrides,
  };
}

const agentModules: V2ModuleNode[] = [
  makeModule({
    name: 'researcher',
    moduleType: 'agent',
    role: 'Researcher',
    goal: 'Research topics',
    tools: ['web-search'],
    handoff: ['writer'],
  }),
];

const toolModules: V2ModuleNode[] = [
  makeModule({
    name: 'web-search',
    moduleType: 'tool',
    provider: 'google',
    capabilities: ['search'],
  }),
];

const workflowModules: V2ModuleNode[] = [
  makeModule({
    name: 'pipeline',
    moduleType: 'workflow',
    steps: [
      { type: 'StepNode', name: 'step-1', location: loc },
      { type: 'StepNode', name: 'step-2', location: loc },
    ],
    edges: [
      { type: 'EdgeNode', source: 'step-1', target: 'step-2', location: loc },
    ],
  }),
];

const teamModules: V2ModuleNode[] = [
  makeModule({
    name: 'dream-team',
    moduleType: 'team',
    members: ['researcher', 'writer'],
  }),
];

const config: CompilerConfig = { target: 'python', includeComments: true };

describe('PythonTargetHandler', () => {
  it('should generate Python code with class and def execute', () => {
    const target = new PythonTarget();
    const output = target.compile(agentModules, config);

    expect(output).toContain('class');
    expect(output).toContain('def execute');
    expect(output).toContain('"""');
    expect(output).toContain('Generated by MAM Compiler');
    expect(output).toContain('Target: Python');
  });

  it('should generate tool class with provider', () => {
    const target = new PythonTarget();
    const output = target.compile(toolModules, config);

    expect(output).toContain('class');
    expect(output).toContain('google');
    expect(output).toContain('def execute');
  });

  it('should generate workflow with STEPS and EDGES', () => {
    const target = new PythonTarget();
    const output = target.compile(workflowModules, config);

    expect(output).toContain('class');
    expect(output).toContain('STEPS');
    expect(output).toContain('EDGES');
    expect(output).toContain('step-1');
    expect(output).toContain('step-2');
  });

  it('should generate team with MEMBERS', () => {
    const target = new PythonTarget();
    const output = target.compile(teamModules, config);

    expect(output).toContain('class');
    expect(output).toContain('MEMBERS');
  });
});

describe('JavaScriptTargetHandler', () => {
  it('should generate JS code with class and module.exports', () => {
    const target = new JavaScriptTarget();
    const output = target.compile(agentModules, config);

    expect(output).toContain('class');
    expect(output).toContain('module.exports');
    expect(output).toContain('constructor');
    expect(output).toContain('execute');
    expect(output).toContain('Generated by MAM Compiler');
    expect(output).toContain('Target: JavaScript');
    expect(output).toContain('"use strict"');
  });

  it('should include role and goal in constructor', () => {
    const target = new JavaScriptTarget();
    const output = target.compile(agentModules, config);

    expect(output).toContain('this.role');
    expect(output).toContain('this.goal');
    expect(output).toContain('Researcher');
    expect(output).toContain('Research topics');
  });

  it('should generate policy with check method', () => {
    const policyModules: V2ModuleNode[] = [
      makeModule({
        name: 'access-policy',
        moduleType: 'policy',
        allow: ['read', 'write'],
        deny: ['delete'],
      }),
    ];

    const target = new JavaScriptTarget();
    const output = target.compile(policyModules, config);

    expect(output).toContain('check');
    expect(output).toContain('this.deny');
    expect(output).toContain('this.allow');
  });
});

