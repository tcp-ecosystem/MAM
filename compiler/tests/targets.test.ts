describe('OpenAITargetHandler', () => {
  it('should generate OpenAI SDK code with Agent and Runner', () => {
    const target = new OpenAITarget();
    const output = target.compile(agentModules, config);

    expect(output).toContain('Agent(');
    expect(output).toContain('Runner');
    expect(output).toContain('from agents import');
    expect(output).toContain('Generated by MAM Compiler');
    expect(output).toContain('Target: OpenAI Agents SDK');
  });

  it('should generate function_tool decorators for tools', () => {
    const target = new OpenAITarget();
    const output = target.compile(agentModules, config);

    expect(output).toContain('@function_tool');
    expect(output).toContain('async def');
  });

  it('should generate tool function with return type', () => {
    const target = new OpenAITarget();
    const output = target.compile(toolModules, config);

    expect(output).toContain('@function_tool');
    expect(output).toContain('def');
    expect(output).toContain('-> str');
  });
});

