  private compileGeneric(mod: V2ModuleNode, indent: number, config: CompilerConfig): { code: string[]; demo: string[] } {
    const pad = ' '.repeat(indent);
    const cls = this.className(mod.name, 'Module');
    const demoVar = this.newVar();
    const inputs = mod.inputs?.map(i => `Port::new("${this.esc(i.name)}", "${this.esc(i.type || 'unknown')}", ${i.required ? 'true' : 'false'})`).join(', ') || '';
    const outputs = mod.outputs?.map(o => `Port::new("${this.esc(o.name)}", "${this.esc(o.type || 'unknown')}", false)`).join(', ') || '';
    const caps = mod.capabilities?.map(c => `"${this.esc(c)}".to_string()`).join(', ') || '';
    const required = mod.inputs?.filter(i => i.required) || [];

    const code = [
      `#[derive(Debug, Clone)]`,
      `pub struct ${cls}Module {`,
      `${pad}pub name: String,`,
      `${pad}pub description: String,`,
      `${pad}pub inputs: Vec<Port>,`,
      `${pad}pub outputs: Vec<Port>,`,
      `${pad}pub capabilities: Vec<String>,`,
      '}',
      '',
      `impl ${cls}Module {`,
      `${pad}pub fn new() -> Self {`,
      `${pad}${pad}Self {`,
      `${pad}${pad}${pad}name: "${this.esc(mod.name)}".to_string(),`,
      `${pad}${pad}${pad}description: "${this.esc(mod.description || '')}".to_string(),`,
      `${pad}${pad}${pad}inputs: vec![${inputs}],`,
      `${pad}${pad}${pad}outputs: vec![${outputs}],`,
      `${pad}${pad}${pad}capabilities: vec![${caps}],`,
      `${pad}${pad}}`,
      `${pad}}`,
      '',
      `${pad}pub fn run(&self, inputs: &HashMap<String, String>) -> ModuleResult {`,
      `${pad}${pad}let missing: Vec<String> = self`,
      `${pad}${pad}${pad}.inputs`,
      `${pad}${pad}${pad}.iter()`,
      `${pad}${pad}${pad}.filter(|p| p.required && !inputs.contains_key(&p.name))`,
      `${pad}${pad}${pad}.map(|p| p.name.clone())`,
      `${pad}${pad}${pad}.collect();`,
      `${pad}${pad}if !missing.is_empty() {`,
      `${pad}${pad}${pad}return ModuleResult { success: false, error: Some(format!("Missing required inputs: {}", missing.join(", "))), outputs: HashMap::new() };`,
      `${pad}${pad}}`,
      `${pad}${pad}let mut outputs: HashMap<String, String> = HashMap::new();`,
      `${pad}${pad}for o in &self.outputs { outputs.insert(o.name.clone(), String::new()); }`,
      `${pad}${pad}for (k, v) in inputs {`,
      `${pad}${pad}${pad}outputs.entry(k.clone()).or_insert_with(|| v.clone());`,
      `${pad}${pad}}`,
      `${pad}${pad}ModuleResult { success: true, error: None, outputs }`,
      `${pad}}`,
      '}',
      '',
      'impl Default for ' + cls + 'Module {',
      `${pad}fn default() -> Self { Self::new() }`,
      '}',
    ];

    const demo: string[] = [
      `let ${demoVar} = ${cls}Module::new();`,
      `let mut ${demoVar}_inputs: HashMap<String, String> = HashMap::new();`,
      ...required.map(i => `${demoVar}_inputs.insert("${this.esc(i.name)}".to_string(), "demo".to_string());`),
      `println!("{}", ${demoVar}.run(&${demoVar}_inputs));`,
    ];

    return { code, demo };
  }

  private generateMain(modules: V2ModuleNode[], indent: number): string[] {
    const pad = ' '.repeat(indent);
    const demos: string[] = [];

    for (const mod of modules) {
      demos.push(...this.compileModule(mod, indent, { target: 'rust' } as CompilerConfig).demo);
    }

    return [
      '',
      ...this.topoSort(indent),
      '',
      'fn main() -> Result<(), MAMError> {',
      `${pad}println!("Registry: {}", registry().join(", "));`,
      ...demos.map(d => pad + d),
      `${pad}Ok(())`,
      '}',
    ];
  }
