  private topoSort(indent: number): string[] {
    const pad = ' '.repeat(indent);
    return [
      '/// Kahn topological sort. Returns (order, has_cycle).',
      'fn topo_sort(nodes: &[String], edges: &[Edge]) -> (Vec<String>, bool) {',
      `${pad}let mut indegree: HashMap<String, usize> = HashMap::new();`,
      `${pad}let mut adj: HashMap<String, Vec<String>> = HashMap::new();`,
      `${pad}for n in nodes {`,
      `${pad}${pad}indegree.insert(n.clone(), 0);`,
      `${pad}${pad}adj.insert(n.clone(), Vec::new());`,
      `${pad}}`,
      `${pad}for e in edges {`,
      `${pad}${pad}if !adj.contains_key(&e.source) || !indegree.contains_key(&e.target) {`,
      `${pad}${pad}${pad}continue;`,
      `${pad}${pad}}`,
      `${pad}${pad}adj.get_mut(&e.source).unwrap().push(e.target.clone());`,
      `${pad}${pad}*indegree.get_mut(&e.target).unwrap() += 1;`,
      `${pad}}`,
      `${pad}let mut queue: VecDeque<String> = VecDeque::new();`,
      `${pad}for n in nodes {`,
      `${pad}${pad}if *indegree.get(n).unwrap() == 0 { queue.push_back(n.clone()); }`,
      `${pad}}`,
      `${pad}let mut order = Vec::new();`,
      `${pad}while let Some(u) = queue.pop_front() {`,
      `${pad}${pad}order.push(u.clone());`,
      `${pad}${pad}for v in adj.get(&u).cloned().unwrap_or_default() {`,
      `${pad}${pad}${pad}let d = indegree.get_mut(&v).unwrap();`,
      `${pad}${pad}${pad}*d -= 1;`,
      `${pad}${pad}${pad}if *d == 0 { queue.push_back(v); }`,
      `${pad}${pad}}`,
      `${pad}}`,
      `${pad}(order, order.len() != nodes.len())`,
      '}',
    ];
  }

  private compileAgent(mod: V2AgentNode, indent: number, config: CompilerConfig): { code: string[]; demo: string[] } {
    const pad = ' '.repeat(indent);
    const cls = this.className(mod.name, 'Agent');
    const demoVar = this.newVar();
    const tools = mod.tools?.map(t => `"${this.esc(t)}".to_string()`).join(', ') || '';
    const handoff = mod.handoff?.map(h => `"${this.esc(h)}".to_string()`).join(', ') || '';
    const memName = mod.memory?.name || mod.memory?.type || '';
    const memInit = memName
      ? `${pad}${pad}${pad}memory: Some("${this.esc(memName)}".to_string()),`
      : `${pad}${pad}${pad}memory: None,`;
    const executeBlock = memName
      ? [
          `${pad}pub fn execute(&self, task: &str) -> AgentResult {`,
          `${pad}${pad}let mut result = format!("[{}] completed '{}' toward goal: {}", self.role, task, self.goal);`,
          `${pad}${pad}if let Some(m) = &self.memory {`,
          `${pad}${pad}${pad}result.push_str(&format!(" | logged to memory: {}", m));`,
          `${pad}${pad}}`,
          `${pad}${pad}AgentResult {`,
          `${pad}${pad}${pad}success: true,`,
          `${pad}${pad}${pad}task: task.to_string(),`,
          `${pad}${pad}${pad}result,`,
          `${pad}${pad}${pad}tool: self.tools.first().cloned(),`,
          `${pad}${pad}}`,
          `${pad}}`,
        ]
      : [
          `${pad}pub fn execute(&self, task: &str) -> AgentResult {`,
          `${pad}${pad}AgentResult {`,
          `${pad}${pad}${pad}success: true,`,
          `${pad}${pad}${pad}task: task.to_string(),`,
          `${pad}${pad}${pad}result: format!("[{}] completed '{}' toward goal: {}", self.role, task, self.goal),`,
          `${pad}${pad}${pad}tool: self.tools.first().cloned(),`,
          `${pad}${pad}}`,
          `${pad}}`,
        ];

    const code = [
      `#[derive(Debug, Clone)]`,
      `pub struct ${cls}Agent {`,
      `${pad}pub name: String,`,
      `${pad}pub role: String,`,
      `${pad}pub goal: String,`,
      `${pad}pub tools: Vec<String>,`,
      `${pad}pub handoff: Vec<String>,`,
      `${pad}pub memory: Option<String>,`,
      '}',
      '',
      `impl ${cls}Agent {`,
      `${pad}pub fn new() -> Self {`,
      `${pad}${pad}Self {`,
      `${pad}${pad}${pad}name: "${this.esc(mod.name)}".to_string(),`,
      `${pad}${pad}${pad}role: "${this.esc(mod.role || '')}".to_string(),`,
      `${pad}${pad}${pad}goal: "${this.esc(mod.goal || '')}".to_string(),`,
      `${pad}${pad}${pad}tools: vec![${tools}],`,
      `${pad}${pad}${pad}handoff: vec![${handoff}],`,
      memInit,
      `${pad}${pad}}`,
      `${pad}}`,
      '',
      ...executeBlock,
      '',
      `${pad}pub fn role(&self) -> &str { &self.role }`,
      `${pad}pub fn goal(&self) -> &str { &self.goal }`,
      '}',
      '',
      'impl Default for ' + cls + 'Agent {',
      `${pad}fn default() -> Self { Self::new() }`,
      '}',
    ];

    const demo = [
      `let ${demoVar} = ${cls}Agent::new();`,
      `println!("{}", ${demoVar}.execute("demo task"));`,
    ];

    return { code, demo };
  }

  private compileTool(mod: V2ToolNode, indent: number, config: CompilerConfig): { code: string[]; demo: string[] } {
    const pad = ' '.repeat(indent);
    const cls = this.className(mod.name, 'Tool');
    const demoVar = this.newVar();
    const caps = mod.capabilities?.map(c => `"${this.esc(c)}".to_string()`).join(', ') || '';
    const firstCap = mod.capabilities && mod.capabilities.length > 0 ? mod.capabilities[0] : 'invoke';

    const code = [
      `#[derive(Debug, Clone)]`,
      `pub struct ${cls}Tool {`,
      `${pad}pub name: String,`,
      `${pad}pub provider: String,`,
      `${pad}pub capabilities: Vec<String>,`,
      '}',
      '',
      `impl ${cls}Tool {`,
      `${pad}pub fn new() -> Self {`,
      `${pad}${pad}Self {`,
      `${pad}${pad}${pad}name: "${this.esc(mod.name)}".to_string(),`,
      `${pad}${pad}${pad}provider: "${this.esc(mod.provider || '')}".to_string(),`,
      `${pad}${pad}${pad}capabilities: vec![${caps}],`,
      `${pad}${pad}}`,
      `${pad}}`,
      '',
      `${pad}pub fn invoke(&self, action: &str, kwargs: &HashMap<String, String>) -> ToolResult {`,
      `${pad}${pad}if !self.capabilities.contains(&action.to_string()) {`,
      `${pad}${pad}${pad}return ToolResult {`,
      `${pad}${pad}${pad}${pad}success: false,`,
      `${pad}${pad}${pad}${pad}action: action.to_string(),`,
      `${pad}${pad}${pad}${pad}result: format!("Action '{}' is not a capability. Available: {}", action, self.capabilities.join(", ")),`,
      `${pad}${pad}${pad}};`,
      `${pad}${pad}}`,
      `${pad}${pad}ToolResult {`,
      `${pad}${pad}${pad}success: true,`,
      `${pad}${pad}${pad}action: action.to_string(),`,
      `${pad}${pad}${pad}result: format!("[{}] invoked '{}' with {} parameter(s)", self.provider, action, kwargs.len()),`,
      `${pad}${pad}}`,
      `${pad}}`,
      '}',
      '',
      'impl Default for ' + cls + 'Tool {',
      `${pad}fn default() -> Self { Self::new() }`,
      '}',
    ];

    const demo = [
      `let ${demoVar} = ${cls}Tool::new();`,
      `println!("{}", ${demoVar}.invoke("${this.esc(firstCap)}", &HashMap::new()));`,
      `println!("{}", ${demoVar}.invoke("not-a-capability", &HashMap::new()));`,
    ];

    return { code, demo };
  }

